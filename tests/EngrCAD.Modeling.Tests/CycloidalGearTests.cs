    // ---- the identities, as arithmetic ----

    [Fact]
    public void SpecIdentities_HoldAsArithmetic()
    {
        var spec = new CycloidalGearSpec(module: 2, teeth: 24, generatingCircleDiameter: 10);

        Assert.Equal(48, spec.PitchDiameter, 12);
        Assert.Equal(24, spec.PitchRadius, 12);
        Assert.Equal(2 * Math.PI, spec.CircularPitch, 12);
        Assert.Equal(5, spec.GeneratingCircleRadius, 12);

        // An epicycloid of a rolling circle of radius rho reaches r + 2*rho and no further,
        // and a hypocycloid reaches |r - 2*rho| - the two limits the addendum and the
        // dedendum are refused against.
        Assert.Equal(10, spec.MaximumAddendum, 12);
        Assert.Equal(Math.Abs(24 - 10), spec.DeepestFlankRadius, 12);

        // The radial-flank identity is rho = r/2, i.e. a describing circle whose DIAMETER
        // equals the pitch radius.
        Assert.Equal(spec.PitchRadius, spec.RadialFlankGeneratingDiameter, 12);
        Assert.False(spec.HasRadialFlanks);
        Assert.True(CycloidalGearSpec.WithRadialFlanks(2, 24).HasRadialFlanks);
        Assert.Equal(spec.PitchRadius / 2,
            CycloidalGearSpec.WithRadialFlanks(2, 24).GeneratingCircleRadius, 12);

        // Backlash comes off the tooth thickness at the pitch circle, half from each flank.
        var thinned = spec with { BacklashAllowance = 0.08 };
        Assert.Equal(Math.PI - 0.08, thinned.ToothThicknessAtPitch, 12);
        Assert.Equal((Math.PI - 0.08) / (2 * 24), thinned.HalfToothAngle, 12);
    }

    [Fact]
    public void Pair_TakesTheClassicClockDescribingCircle()
    {
        // Half the PINION's pitch diameter, so the pinion's leaves are radial and the wheel's
        // flanks are not - the asymmetry is the point.
        var mesh = CycloidalGears.Pair(module: 1, pinionTeeth: 10, wheelTeeth: 40);
        Assert.Equal(5, mesh.GeneratingCircleDiameter, 12);
        Assert.True(mesh.Pinion.HasRadialFlanks);
        Assert.False(mesh.Wheel.HasRadialFlanks);
        Assert.Equal(25, mesh.CentreDistance, 12);
        Assert.Equal(4, mesh.GearRatio, 12);
    }

    // ---- the radial-flank identity, MEASURED off the generated sketch ----
    //
    // A hypocycloid generated by a circle of half the pitch radius is a straight line through
    // the gear centre. Nothing in the factory special-cases that: the general cycloid formula
    // and the general biarc fit reach it on their own, which is exactly why measuring it off
    // the OUTPUT is a test rather than a restatement. The measurement asks the sketch's own
    // exact signed distance where the boundary crosses a circle of a given radius, and a
    // radial flank puts every one of those crossings on the same ray.

    [Fact]
    public void RadialFlanks_MeasureStraightOffTheGeneratedSketch()
    {
        var spec = CycloidalGearSpec.WithRadialFlanks(module: 1, teeth: 12);
        var profile = CycloidalGears.Spur(spec);
        double drift = FlankAngularDrift(profile, out double psi);

        // The exact-line case: the crossings sit on the ray at -psi to round-off, and the
        // fit produced literal straight segments (2 collinear halves of one biarc).
        Assert.True(drift < 1e-12, $"radial flank drifted {drift:0.###e0} rad from the ray at -{psi}");
        Assert.Equal(2, profile.CurvesPerFlank);
        Assert.All(FirstFlankPieces(profile), piece => Assert.IsType<Line2d>(piece));
    }

    [Fact]
    public void NonRadialFlanks_DriftMeasurably_SoTheInstrumentCanSeeAFlank()
    {
        // The same measurement on a gear cut by the same describing circle but with four times
        // the teeth: its flanks are hypocycloids, not lines, and the tooth WIDENS toward the
        // root (the flank leans away from the tooth centre going in).
        var mesh = CycloidalGears.Pair(module: 1, pinionTeeth: 12, wheelTeeth: 48);
        var wheel = CycloidalGears.Spur(mesh.Wheel);
        double drift = FlankAngularDrift(wheel, out _);
        Assert.True(drift > 1e-3,
            $"a hypocycloidal flank should drift measurably off the radial ray; measured {drift:0.###e0} rad");

        // Direction: the crossing angle at the root is FURTHER from the tooth centre than at
        // the pitch circle, i.e. the tooth is thicker at the root.
        var region = wheel.Sketch.ToRegion();
        double r = mesh.Wheel.PitchRadius;
        double rf = mesh.Wheel.RootDiameter / 2;
        double psi = mesh.Wheel.HalfToothAngle;
        double atPitch = -RightFlankCrossing(region, r - 1e-6, psi);
        double atRoot = -RightFlankCrossing(region, rf + 0.02, psi);
        Assert.True(atRoot > atPitch,
            $"the flank should lean away from the tooth centre going inward: {atRoot} vs {atPitch}");
    }

    [Fact]
    public void ToothThicknessAtThePitchCircle_MeasuresTheSpec()
    {
        foreach (double backlash in new[] { 0.0, 0.05 })
        {
            var spec = new CycloidalGearSpec(module: 2, teeth: 20, generatingCircleDiameter: 12)
            { BacklashAllowance = backlash };
            var profile = CycloidalGears.Spur(spec);
            var region = profile.Sketch.ToRegion();
            double r = spec.PitchRadius;
            double psi = spec.HalfToothAngle;
            // Probe just inside the pitch circle so both flanks are genuine boundary crossings.
            double right = RightFlankCrossing(region, r - 1e-7, psi);
            double left = LeftFlankCrossing(region, r - 1e-7, psi);
            double measured = (left - right) * r;
            Assert.True(Math.Abs(measured - spec.ToothThicknessAtPitch) < 1e-5,
                $"tooth thickness measured {measured} against {spec.ToothThicknessAtPitch} "
                + $"(backlash {backlash})");
        }
    }

    // ---- the fit contract ----

    [Fact]
    public void FitDeviation_HonorsItsStatedTolerance()
    {
        var spec = new CycloidalGearSpec(module: 2, teeth: 20, generatingCircleDiameter: 12);
        var loose = CycloidalGears.Spur(spec, fitTolerance: 2e-3);
        var tight = CycloidalGears.Spur(spec, fitTolerance: 2e-6);
        Assert.True(loose.MaxFitDeviation <= loose.FitTolerance,
            $"{loose.MaxFitDeviation} exceeds {loose.FitTolerance}");
        Assert.True(tight.MaxFitDeviation <= tight.FitTolerance,
            $"{tight.MaxFitDeviation} exceeds {tight.FitTolerance}");
        // A tighter tolerance genuinely buys arcs (so the reported deviation is not a constant
        // the fit reaches whatever it is asked for).
        Assert.True(tight.CurvesPerFace > loose.CurvesPerFace);
        Assert.True(tight.MaxFitDeviation < loose.MaxFitDeviation);
        // The default is module * 1e-4.
        Assert.Equal(2e-4, CycloidalGears.Spur(spec).FitTolerance, 15);
    }

    [Fact]
    public void ClosedFormArea_MatchesTheGeneratedSketch()
    {
        // Both cycloid families integrate in closed form under Green's theorem, so the profile
        // states an EXACT area for the ideal outline; the sketch's own area may differ only by
        // the fit deviation spread over the fitted length.
        foreach (var spec in new[]
        {
            CycloidalGearSpec.WithRadialFlanks(module: 1, teeth: 12),
            new CycloidalGearSpec(module: 2, teeth: 20, generatingCircleDiameter: 12),
            new CycloidalGearSpec(module: 1, teeth: 48, generatingCircleDiameter: 5),
            new CycloidalGearSpec(module: 2, teeth: 20, generatingCircleDiameter: 12)
                { RootFilletCoefficient = 0 },
        })
        {
            var profile = CycloidalGears.Spur(spec);
            double measured = profile.Sketch.Area();
            double bound = profile.MaxFitDeviation * FittedLength(profile) * 2 + 1e-9;
            Assert.True(Math.Abs(measured - profile.ClosedFormArea) < bound,
                $"z={spec.Teeth}: sketch area {measured} vs closed form {profile.ClosedFormArea} "
                + $"(bound {bound})");
        }
    }

    [Fact]
    public void RadialFlank_ContributesExactlyNothingToTheClosedFormArea()
    {
        // The hypocycloid's Green term carries the factor (r - 2*rho), which is exactly zero at
        // the radial-flank identity - a line through the origin encloses nothing. Building the
        // same gear with a slightly smaller describing circle must move the area.
        var radial = CycloidalGears.Spur(CycloidalGearSpec.WithRadialFlanks(1, 12));
        var curved = CycloidalGears.Spur(new CycloidalGearSpec(1, 12, generatingCircleDiameter: 5.0));
        Assert.True(Math.Abs(radial.ClosedFormArea - curved.ClosedFormArea) > 1e-3,
            "a different describing circle must change the enclosed area");
    }

    // ---- conjugate action, from CONTACT at the DESIGN centre distance ----
    //
    // Cycloidal conjugacy is a property of the PAIR: one describing circle traces the wheel's
    // epicycloidal face and the pinion's hypocycloidal flank, so sharing it is the law of
    // gearing. Unlike an involute pair, the ratio is constant only at the design centre
    // distance (the describing circle has to roll on BOTH pitch circles), so the measurement
    // is made there and backlash comes from THINNING the teeth instead - which is exact,
    // because rotating a cycloid about its own pitch circle's centre is the same cycloid at
    // another phase.
    //
    // The mechanism solver is deliberately not the instrument: Coupling.Gear ENFORCES a ratio.
    // Contact through the sketch's exact signed distance derives it from the drawn teeth.

    private const double ConjugacySweepPitches = 1.2;

    [Fact]
    public void ConjugateAction_RatioConstantThroughToothHandover()
    {
        var mesh = CycloidalGears.Pair(module: 1, pinionTeeth: 10, wheelTeeth: 30);
        double spread = ContactSpread(WithBacklash(mesh.Pinion), WithBacklash(mesh.Wheel),
            extraCentreDistance: 0, sweepPitches: ConjugacySweepPitches, samples: 8);
        // Tolerance derivation: each flank deviates <= its fit tolerance (1e-4) from the true
        // cycloid, boundary sampling at 0.02 mm under a relative contact curvature radius of a
        // few mm adds ~1e-5, and the pinion's base radius for the angular conversion is 5 mm -
        // so ~4e-5 rad of position uncertainty. Asserted at 2e-4 (5x headroom); measured 4e-6.
        Assert.True(spread < 2e-4, $"transmission varied by {spread:0.###e0} rad across the sweep");
    }

    [Fact]
    public void ConjugateAction_WrongDescribingCircle_IsSeenByTheSameInstrument()
    {
        // The mutation: a wheel cut with a describing circle the pinion was not cut with. Both
        // gears are still perfectly good cycloidal gears; only the PAIRING is broken, which is
        // precisely the failure a ratio-only check cannot see.
        var mesh = CycloidalGears.Pair(module: 1, pinionTeeth: 10, wheelTeeth: 30);
        var wrongWheel = new CycloidalGearSpec(1, 30, mesh.GeneratingCircleDiameter * 1.6);
        double conjugate = ContactSpread(WithBacklash(mesh.Pinion), WithBacklash(mesh.Wheel),
            0, 0.6, 6);
        double mutated = ContactSpread(WithBacklash(mesh.Pinion), WithBacklash(wrongWheel),
            0, 0.6, 6);
        Assert.True(mutated > 50 * conjugate,
            $"a wrong describing circle read {mutated:0.###e0} rad against the conjugate pair's "
            + $"{conjugate:0.###e0} - the instrument cannot see flank FORM");
    }

    [Fact]
    public void CentreDistanceError_RipplesTheRatio_TheHonestContrastWithTheInvolute()
    {
        // NOT a defect: an involute pair is centre-distance invariant because its ratio is set
        // by the base circles, while a cycloidal pair's describing circle must roll on both
        // pitch circles at once. Mounted long, the pair still runs and the ratio ripples. The
        // sensitivity is measured here so the docs can state a number instead of a warning.
        var mesh = CycloidalGears.Pair(module: 1, pinionTeeth: 10, wheelTeeth: 30);
        var pinion = WithBacklash(mesh.Pinion);
        var wheel = WithBacklash(mesh.Wheel);
        double atDesign = ContactSpread(pinion, wheel, 0, 0.6, 6);
        double mountedLong = ContactSpread(pinion, wheel, 0.3, 0.6, 6);
        Assert.True(mountedLong > 50 * atDesign,
            $"0.3 mm of centre-distance error read {mountedLong:0.###e0} rad against "
            + $"{atDesign:0.###e0} at the design distance");
    }

