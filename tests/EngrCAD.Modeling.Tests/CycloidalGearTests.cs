        Assert.Equal(mesh.Wheel.AddendumCoefficient + 0.05, mesh.Pinion.DedendumCoefficient, 12);
        Assert.Equal(mesh.Pinion.AddendumCoefficient + 0.05, mesh.Wheel.DedendumCoefficient, 12);
