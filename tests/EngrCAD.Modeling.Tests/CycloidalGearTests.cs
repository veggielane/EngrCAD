    [Fact]
    public void Bs978Part2_DerivesEachDedendumFromItsMatesAddendum()
    {
        var mesh = ClockGearProportions.Bs978Part2(module: 0.5, pinionLeaves: 8, wheelTeeth: 60);
        Assert.True(mesh.Pinion.HasRadialFlanks);
        Assert.Equal(ClockGearProportions.PinionAddendumCoefficient(8), mesh.Pinion.AddendumCoefficient, 12);
        Assert.Equal(ClockGearProportions.WheelAddendumCoefficient(8), mesh.Wheel.AddendumCoefficient, 12);
        // A member's dedendum clears its MATE's addendum plus the clearance - derived, never a
