    // ------------------------------------------------------------------ helpers

    private static CycloidalGearSpec WithBacklash(CycloidalGearSpec spec) =>
        spec with { BacklashAllowance = 0.03 };

    /// <summary>The greatest angular drift of the right flank's boundary crossings off the
    /// radial ray at −ψ, measured over radii spanning the flank.</summary>
    private static double FlankAngularDrift(CycloidalProfile profile, out double psi)
    {
        var region = profile.Sketch.ToRegion();
        double r = profile.Spec.PitchRadius;
        double rf = profile.Spec.RootDiameter / 2;
        psi = profile.Spec.HalfToothAngle;
        // Stay clear of the root fillet, which is an arc by design and not part of the flank.
        double low = rf + 0.35 * (r - rf);
        double worst = 0;
        for (int i = 0; i <= 12; i++)
        {
            double radius = low + (r - 1e-7 - low) * i / 12;
            worst = Math.Max(worst, Math.Abs(RightFlankCrossing(region, radius, psi) + psi));
        }
        return worst;
    }

    private static IEnumerable<Curve2d> FirstFlankPieces(CycloidalProfile profile)
    {
        // The canonical tooth is: root fillet, flank chain, face chain, tip arc, ... - so the
        // flank pieces follow the single fillet arc.
        var curves = profile.Sketch.ToCurves();
        return curves.Skip(1).Take(profile.CurvesPerFlank);
    }

    /// <summary>Bisects the outline crossing along the circle of radius <paramref name="radius"/>
    /// between the tooth centre (inside) and the gap at −(ψ + a pitch fraction) (outside).</summary>
    private static double RightFlankCrossing(IPlanarRegion region, double radius, double psi)
        => BisectCrossing(region, radius, 0, -(psi + 0.35 * psi + 0.02 / Math.Max(radius, 1e-9)));

    private static double LeftFlankCrossing(IPlanarRegion region, double radius, double psi)
        => BisectCrossing(region, radius, 0, psi + 0.35 * psi + 0.02 / Math.Max(radius, 1e-9));

    private static double BisectCrossing(IPlanarRegion region, double r, double inside, double outside)
    {
        double At(double theta) => region.SignedDistance(new Vector2d(r * Math.Cos(theta), r * Math.Sin(theta)));
        Assert.True(At(inside) < 0, "inside probe is not inside");
        Assert.True(At(outside) > 0, "outside probe is not outside");
        for (int i = 0; i < 60; i++)
        {
            double mid = (inside + outside) / 2;
            if (At(mid) < 0) inside = mid; else outside = mid;
        }
        return (inside + outside) / 2;
    }

    /// <summary>Total fitted (cycloidal) length in the outline — the length the fit deviation
    /// can act over when the sketch's area is compared against the closed form.</summary>
    private static double FittedLength(CycloidalProfile profile)
    {
        double r = profile.Spec.PitchRadius;
        double span = profile.Spec.TipDiameter / 2 - profile.Spec.RootDiameter / 2;
        return 2 * profile.Spec.Teeth * span * 1.6 + r;   // generous: chords are shorter than this
    }

    /// <summary>
    /// The spread of the drive-flank contact offset β* over a sweep of pinion angles: the wheel
    /// is rotated toward contact and the touching angle found by bisection of the clearance —
    /// the minimum of the pinion region's exact signed distance over the wheel outline's
    /// sampled points. A constant β* IS constant transmission.
    /// </summary>
    private static double ContactSpread(CycloidalGearSpec pinionSpec, CycloidalGearSpec wheelSpec,
        double extraCentreDistance, double sweepPitches, int samples)
    {
        var pinion = CycloidalGears.Spur(pinionSpec);
        var wheel = CycloidalGears.Spur(wheelSpec);
        var region = pinion.Sketch.ToRegion();
        double a = (pinionSpec.PitchDiameter + wheelSpec.PitchDiameter) / 2 + extraCentreDistance;
        double ratio = (double)pinionSpec.Teeth / wheelSpec.Teeth;
        double wheelPitch = 2 * Math.PI / wheelSpec.Teeth;
        double alignment = Math.PI - wheelPitch / 2;   // a wheel gap on the line of centres
        double tipRadius = pinionSpec.TipDiameter / 2 + 0.05;
        double sweepRange = sweepPitches * 2 * Math.PI / pinionSpec.Teeth;

        var points = new List<Vector2d>();
        foreach (var curve in wheel.Sketch.ToCurves())
        {
            double length = Curve2dLength(curve);
            int n = Math.Max(2, (int)Math.Ceiling(length / 0.02));
            for (int i = 0; i < n; i++)
                points.Add(curve.PointAt((double)i / n));
        }

        double Clearance(double phi1, double phi2)
        {
            double c1 = Math.Cos(-phi1), s1 = Math.Sin(-phi1);
            double c2 = Math.Cos(phi2), s2 = Math.Sin(phi2);
            double min = 1.0;
            foreach (var p in points)
            {
                double wx = a + p.X * c2 - p.Y * s2;
                double wy = p.X * s2 + p.Y * c2;
                if (wx * wx + wy * wy > tipRadius * tipRadius)
                    continue;
                var q = new Vector2d(wx * c1 - wy * s1, wx * s1 + wy * c1);
                min = Math.Min(min, region.SignedDistance(q));
                if (min < -0.05)
                    break;
            }
            return min;
        }

        double lowest = double.PositiveInfinity, highest = double.NegativeInfinity;
        double? previous = null;
        for (int step = 0; step < samples; step++)
        {
            double phi1 = sweepRange * step / (samples - 1);
            double basePhi2 = alignment - ratio * phi1;
            double lo, hi;
            if (previous is double seed
                && Clearance(phi1, basePhi2 + seed - 0.004) > 0
                && Clearance(phi1, basePhi2 + seed + 0.004) < 0)
            {
                lo = seed - 0.004;
                hi = seed + 0.004;
            }
            else
            {
                double bestBeta = double.NaN, bestG = double.NegativeInfinity;
                for (double beta = -0.05; beta <= 0.05; beta += 0.001)
                {
                    double g = Clearance(phi1, basePhi2 + beta);
                    if (g > bestG) { bestG = g; bestBeta = beta; }
                }
                Assert.True(bestG > 0, $"no clearance window found at phi1={phi1}");
                lo = bestBeta;
                hi = bestBeta;
                while (Clearance(phi1, basePhi2 + hi) > 0)
                {
                    lo = hi;
                    hi += 0.002;
                    Assert.True(hi < 0.15, "contact edge not found");
                }
            }
            for (int i = 0; i < 45; i++)
            {
                double mid = (lo + hi) / 2;
                if (Clearance(phi1, basePhi2 + mid) > 0) lo = mid; else hi = mid;
            }
            double contact = (lo + hi) / 2;
            lowest = Math.Min(lowest, contact);
            highest = Math.Max(highest, contact);
            previous = contact;
        }
        return highest - lowest;
    }

    internal static double Curve2dLength(Curve2d curve) => curve switch
    {
        Line2d line => (line.End - line.Start).Length,
        Arc2d arc => arc.Length,
        _ => curve.ArcLength(),
    };
